// Canonical procedures live in CLAUDE.md and .claude/skills/*/SKILL.md.
// These thin adapters share discovery metadata and point agents to those files.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const START = "<!-- Generated agent adapter: start -->";
const END = "<!-- Generated agent adapter: end -->";
export const WORKING_AGREEMENTS = [
  "- Make a plan before edits.",
  "- Prefer minimal diffs.",
  "- Run unit tests relevant to changed files.",
  "- Ask before adding new dependencies.",
];
const defaultPreamble = `# Working agreements\n\n${WORKING_AGREEMENTS.join("\n")}\n\n`;
const textOf = path => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

function rootAdapter(current) {
  const generated = `${START}
## Project instructions

Read and follow [CLAUDE.md](CLAUDE.md) before working on this project. It is the
canonical project guide; its relative paths resolve from the repository root.

Skill procedures are maintained in \`.claude/skills/*/SKILL.md\`. The matching
\`.agents/skills/*/SKILL.md\` files are generated entry points: open their linked
canonical procedure before following a skill. Resolve that procedure's relative
resources against its canonical directory, including its tracked \`log.md\`.

Edit canonical procedures directly. After changing skill discovery metadata or
adding a skill, run \`node src/sync-agent-instructions.mjs --write\` and commit the
adapters. Verify them with \`node src/sync-agent-instructions.mjs --check\`.
Keep these working agreements and any personal preamble outside the generated
markers; regeneration preserves them. Never put credentials in an adapter.
${END}`;
  if (current === null) return `${defaultPreamble}${generated}\n`;
  if (current.split(START).length !== 2 || current.split(END).length !== 2 || current.indexOf(START) > current.indexOf(END)) {
    throw new Error("AGENTS.md has missing or duplicate generated markers. Preserve its working agreements and personal instructions before migrating it to a thin adapter.");
  }
  const preamble = current.slice(0, current.indexOf(START));
  for (const agreement of WORKING_AGREEMENTS) {
    if (!preamble.includes(agreement)) throw new Error(`AGENTS.md must preserve this working agreement above its generated marker: ${agreement}`);
  }
  return preamble + generated + current.slice(current.indexOf(END) + END.length);
}

function skillAdapter(source, name) {
  const frontmatter = source.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
  if (!frontmatter) throw new Error(`.claude/skills/${name}/SKILL.md needs YAML frontmatter for skill discovery.`);
  if (!new RegExp(`^name: ${name}$`, "m").test(frontmatter[1]) || !/^description:\s*\S/m.test(frontmatter[1])) {
    throw new Error(`.claude/skills/${name}/SKILL.md needs name: ${name} and a nonempty description.`);
  }
  return `${frontmatter[0].trimEnd()}

<!-- Generated by src/sync-agent-instructions.mjs; edit the canonical procedure. -->

Read and follow the complete [canonical ${name} procedure](../../../.claude/skills/${name}/SKILL.md)
before doing this task. This adapter is only a discovery entry point.

Resolve all relative paths and supporting resources from the canonical procedure's
directory, not this adapter's directory. Write procedure logs to the canonical
tracked \`log.md\`; do not create a second local log. Read the root
[project guide](../../../CLAUDE.md) for the shared operating rules.
`;
}

export function syncAgentInstructions({ root = fileURLToPath(new URL("../", import.meta.url)), check = true } = {}) {
  root = resolve(root);
  const guide = join(root, "CLAUDE.md");
  if (!existsSync(guide) || !textOf(guide).trim()) throw new Error("Canonical project guide CLAUDE.md is missing or empty.");
  const canonicalDir = join(root, ".claude", "skills");
  const names = readdirSync(canonicalDir, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && existsSync(join(canonicalDir, entry.name, "SKILL.md")))
    .map(entry => entry.name).sort();
  if (!names.length) throw new Error("No canonical .claude/skills/*/SKILL.md procedures found.");
  for (const name of names) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`Invalid canonical skill directory name: ${name}`);
  }
  const targetDir = join(root, ".agents", "skills");
  const extras = existsSync(targetDir) ? readdirSync(targetDir, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && existsSync(join(targetDir, entry.name, "SKILL.md")) && !names.includes(entry.name))
    .map(entry => `.agents/skills/${entry.name}/SKILL.md`) : [];
  if (extras.length) throw new Error(`Adapters have no canonical procedure: ${extras.join(", ")}. Review and remove obsolete adapters or add their canonical procedure; no files were deleted.`);

  const rootPath = join(root, "AGENTS.md");
  const files = [{ path: "AGENTS.md", text: rootAdapter(existsSync(rootPath) ? textOf(rootPath) : null) }];
  for (const name of names) files.push({ path: `.agents/skills/${name}/SKILL.md`, text: skillAdapter(textOf(join(canonicalDir, name, "SKILL.md")), name) });
  // Build and validate every expected adapter before writing any of them.
  const changed = files.filter(file => !existsSync(join(root, file.path)) || textOf(join(root, file.path)) !== file.text);
  if (!check) for (const file of changed) {
    const path = join(root, file.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.text);
  }
  return { ok: !check || !changed.length, skills: names.length, changed: changed.map(file => file.path) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  try {
    if (args.length > 1 || (args.length && !["--check", "--write"].includes(args[0]))) throw new Error("Usage: node src/sync-agent-instructions.mjs [--check|--write]");
    const check = args[0] !== "--write";
    const result = syncAgentInstructions({ check });
    if (!result.ok) {
      console.error(`Agent instruction adapters are missing or stale:\n${result.changed.map(path => `  ${path}`).join("\n")}\nRun node src/sync-agent-instructions.mjs --write and commit the generated adapters.`);
      process.exitCode = 1;
    } else console.log(`Agent instruction adapters ${check ? "verified" : "synchronized"}: ${result.skills} skills, ${result.changed.length} files changed.`);
  } catch (error) {
    console.error(`Agent instruction sync failed: ${error.message}`);
    process.exitCode = 1;
  }
}
